import assert from 'node:assert/strict';
import {finite,extent,median,percentile,rollingMean,wilson,cleanTimeline,segments} from '../web/analysis-math.mjs';
for (const value of [null,undefined,'','  ',NaN,Infinity,true,false]) assert.equal(finite(value),null);
assert.equal(finite(0),0);
assert.deepEqual(extent([null,undefined]),[0,1]);
assert.equal(median([null,0,10]),5);
assert.equal(percentile(null,[1,2]),null);
assert.equal(percentile(7,[7,7,7]),50);
assert.equal(percentile(2,[1,2,2,3]),50);
const rolling = rollingMean([{v:1},{v:null},{v:3},{v:5}], 'v', 3);
assert.deepEqual(rolling[1],{value:1,n:1});
assert.deepEqual(rolling[3],{value:4,n:2});
assert.equal(wilson(0,0),null);
assert.equal(wilson(2,1),null);
assert.ok(wilson(1,1)[0]<25);
assert.ok(wilson(50,100)[0]>40 && wilson(50,100)[1]<60);
const points = cleanTimeline([{gameTime:30,blueGold:100,redGold:null},{gameTime:60,blueGold:200,redGold:100},{gameTime:0,blueGold:0,redGold:0},{gameTime:60,blueGold:250,redGold:100},{gameTime:240,blueGold:500,redGold:300}]);
assert.deepEqual(points.map(p=>[p.gameTime,p.diff]),[[0,0],[60,150],[240,200]]);
assert.equal(segments(points).length,2);
console.log('Analysis math: missing values, tied ranks, rolling windows, intervals and timeline gaps passed.');
